"""Generate MinimaDock's original launcher mark; no image input or tracing.

"Bar M on dock": three rounded bars form an M (the middle one shorter) standing
on a rounded base bar, the dock. Uses only Python's standard library. The same
contours produce an SVG and a cached native Direct2D geometry at 24 DIP.
License: MIT (see ../LICENSE).
"""
from math import cos, sin, pi
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
STEPS = 18  # Segments per round end.


def capsule(x0, y0, x1, y1):
    """Rounded bar; the shorter side is a full semicircle. Clockwise on screen."""
    r = min(x1-x0, y1-y0)/2
    def arc(cx, cy, start):
        return [(cx+r*cos(start+pi*i/STEPS), cy+r*sin(start+pi*i/STEPS)) for i in range(STEPS+1)]
    if y1-y0 >= x1-x0:   # Vertical: round top and bottom.
        return arc((x0+x1)/2, y0+r, pi)+arc((x0+x1)/2, y1-r, 0)
    return arc(x1-r, (y0+y1)/2, -pi/2)+arc(x0+r, (y0+y1)/2, pi/2)


# Coordinates in the 24 DIP launcher box, as approved in the concept sheet.
contours = [
    capsule(4.5, 4.0, 7.7, 15.5),     # Left stroke of the M.
    capsule(10.4, 8.0, 13.6, 15.5),   # Shorter middle stroke.
    capsule(16.3, 4.0, 19.5, 15.5),   # Right stroke.
    capsule(4.5, 17.8, 19.5, 20.4),   # The dock.
]

path = ' '.join('M '+' L '.join(f'{x:.4f},{y:.4f}' for x, y in contour)+' Z'
                for contour in contours)
(ROOT/'assets/minimadock-mark.svg').write_text(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">\n'
    '<title>MinimaDock mark</title>\n'
    '<!-- Original project artwork, generated by tools/Generate-LauncherLogo.py. MIT. -->\n'
    f'<path fill="currentColor" fill-rule="evenodd" d="{path}"/>\n</svg>\n',
    encoding='utf-8')
vertices = [point for contour in contours for point in contour]
offsets = [0]
for contour in contours:
    offsets.append(offsets[-1]+len(contour))
(ROOT/'src/rendering/launcher_logo.h').write_text(
    '// Original project artwork. MIT; see LICENSE.\n'
    '// Generated alongside assets/minimadock-mark.svg by tools/Generate-LauncherLogo.py.\n'
    '#pragma once\n#include <d2d1.h>\n#include <array>\n#include <cstddef>\n'
    'namespace minima::launcher_logo {\n'
    f'inline constexpr std::array<D2D1_POINT_2F,{len(vertices)}> points = {{{{\n'
    + ''.join(f'    {{{x:.4f}f,{y:.4f}f}},\n' for x, y in vertices)
    + '}};\n'
    + f'inline constexpr std::array<std::size_t,{len(offsets)}> offsets = {{{{'
    + ','.join(map(str, offsets)) + '}};\n}\n', encoding='utf-8')
print(f'Generated MinimaDock mark: {len(contours)} contours, {len(vertices)} vertices, 24 DIP.')
