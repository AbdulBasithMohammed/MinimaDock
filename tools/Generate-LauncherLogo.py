"""Generate MinimaDock's original geometric swords; no image input or tracing.

Uses only Python's standard library. The shared polygon data produces an SVG
and a cached native Direct2D geometry at 24 DIP. License: MIT (see ../LICENSE).
"""
from math import cos, sin, pi
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent

# Upright sword: tapered blade, straight guard, narrow grip, diamond pommel.
SWORD = [
    (0, -14), (-1.45, -10.7), (-1.45, 3.2),
    (-3, 3.2), (-3, 4.2), (-.85, 4.2), (-.85, 8.6),
    (-1.25, 8.6), (-1.25, 9.8), (0, 10.9),
    (1.25, 9.8), (1.25, 8.6), (.85, 8.6), (.85, 4.2),
    (3, 4.2), (3, 3.2), (1.45, 3.2), (1.45, -10.7),
]


def rotate(points, angle):
    c, s = cos(angle), sin(angle)
    return [(x*c-y*s, x*s+y*c) for x, y in points]


# Rear blade is split at the crossing, leaving a small optical separation.
# All outer contours are disjoint; inner contours cut transparent blade/grip
# grooves with the renderer's existing even-odd fill rule.
rear_tip = [(0, -14), (-1.45, -10.7), (-1.45, -2),
            (1.45, -2), (1.45, -10.7)]
rear_hilt = [(-1.45, 2)] + SWORD[2:-1] + [(1.45, 2)]
front_groove = [(0, -11), (-.28, -10), (-.28, 2.4),
                (.28, 2.4), (.28, -10)]
rear_groove = [(0, -11), (-.28, -10), (-.28, -2.4),
               (.28, -2.4), (.28, -10)]
grip_groove = [(-.22, 4.9), (-.22, 8), (.22, 8), (.22, 4.9)]
contours = [rotate(SWORD, pi/4), rotate(rear_tip, -pi/4),
            rotate(rear_hilt, -pi/4), rotate(front_groove, pi/4),
            rotate(rear_groove, -pi/4), rotate(grip_groove, pi/4),
            rotate(grip_groove, -pi/4)]
vertices = [point for contour in contours for point in contour]
left, right = min(x for x, y in vertices), max(x for x, y in vertices)
top, bottom = min(y for x, y in vertices), max(y for x, y in vertices)
extent = max(right-left, bottom-top)
cx, cy = (left+right)/2, (top+bottom)/2
contours = [[((x-cx)*24/extent+12, (y-cy)*24/extent+12)
             for x, y in contour] for contour in contours]

path = ' '.join('M '+' L '.join(f'{x:.4f},{y:.4f}' for x, y in contour)+' Z'
                for contour in contours)
(ROOT/'assets/launcher-swords.svg').write_text(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">\n'
    '<title>MinimaDock original geometric crossed swords</title>\n'
    '<!-- Original project artwork, generated by tools/Generate-LauncherLogo.py. MIT. -->\n'
    f'<path fill="currentColor" fill-rule="evenodd" d="{path}"/>\n</svg>\n',
    encoding='utf-8')
vertices = [point for contour in contours for point in contour]
offsets = [0]
for contour in contours:
    offsets.append(offsets[-1]+len(contour))
(ROOT/'src/rendering/launcher_logo.h').write_text(
    '// Original project artwork. MIT; see LICENSE.\n'
    '// Generated alongside assets/launcher-swords.svg by tools/Generate-LauncherLogo.py.\n'
    '#pragma once\n#include <d2d1.h>\n#include <array>\n#include <cstddef>\n'
    'namespace minima::launcher_logo {\n'
    f'inline constexpr std::array<D2D1_POINT_2F,{len(vertices)}> points = {{{{\n'
    + ''.join(f'    {{{x:.4f}f,{y:.4f}f}},\n' for x, y in vertices)
    + '}};\n'
    + f'inline constexpr std::array<std::size_t,{len(offsets)}> offsets = {{{{'
    + ','.join(map(str, offsets)) + '}};\n}\n', encoding='utf-8')
print(f'Generated original swords: {len(contours)} contours, {len(vertices)} vertices, 24 DIP.')
